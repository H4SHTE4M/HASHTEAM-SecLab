cat > .message <<'M_EOF'
你找到我了！

在 Linux 里，以点（.）开头的是隐藏文件，普通的 ls 不会显示它们，
但它们真实存在。「看不见」和「不存在」是两回事——这一点在安全
工作里会反复用到。

验证信息：dotfile-42
把验证信息交给 check 即可过关。
M_EOF
echo "──────────────────────────────────────────────"
